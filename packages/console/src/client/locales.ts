/** The keys this namespace defines. */
export type ConsoleLocaleKey = keyof typeof zh

/**
 * Translate one key of this namespace, with `{name}` interpolation.
 *
 * The seat the workbench's own surfaces take. Declared here rather than as the
 * framework's `PropsLocale<'console'>` so a component can be driven by a spec
 * (and by the settings row's simpler surface) without the slot machinery.
 * @param key - a key of the workbench dictionary.
 * @param params - values for the placeholders.
 * @returns the localized text.
 */
export type Translate = (key: ConsoleLocaleKey, params?: Record<string, unknown>) => string

/** Locale key naming one known event source; an unknown id is shown as declared. */
const SOURCE_KEYS: Readonly<Record<string, ConsoleLocaleKey>> = {
  mail: 'sourceMail',
  webhook: 'sourceWebhook',
  dingtalk: 'sourceDingtalk',
  jira: 'sourceJira',
  manual: 'sourceManual',
  agent: 'sourceAgent',
}

/**
 * Name an event source in the user's words.
 *
 * Not every source is ours (a connector may use its own id), so an unknown id is
 * shown exactly as declared rather than replaced with a generic word that loses
 * the only thing the row said.
 * @param source - the source id a card, notice or log entry carries.
 * @param t - the translate seat.
 * @returns the localized name, or the id when this build has no name for it.
 */
export function sourceLabel(source: string, t: Translate): string {
  const key = SOURCE_KEYS[source]
  return key === undefined ? source : t(key)
}

